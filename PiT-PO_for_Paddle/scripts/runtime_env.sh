#!/usr/bin/env bash
PITPO_PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
export PITPO_STORAGE_ROOT="${PITPO_STORAGE_ROOT:-$PITPO_PROJECT_DIR/.runtime}"
export PITPO_RUNTIME_ROOT="${PITPO_RUNTIME_ROOT:-$PITPO_STORAGE_ROOT}"
export TMPDIR="$PITPO_RUNTIME_ROOT/tmp"
export TMP="$TMPDIR" TEMP="$TMPDIR"
export XDG_CACHE_HOME="$PITPO_STORAGE_ROOT/cache"
export PIP_CACHE_DIR="$XDG_CACHE_HOME/pip"
export HF_HOME="$XDG_CACHE_HOME/huggingface"
export HUGGINGFACE_HUB_CACHE="$HF_HOME/hub"
export PADDLE_HOME="$XDG_CACHE_HOME/paddle"
export PPNLP_HOME="$XDG_CACHE_HOME/paddlenlp"
export PF_HOME="$XDG_CACHE_HOME/paddleformers"
export MODELSCOPE_CACHE="$XDG_CACHE_HOME/modelscope"
export CUDA_CACHE_PATH="$XDG_CACHE_HOME/cuda"
export TRITON_CACHE_DIR="$XDG_CACHE_HOME/triton"
export MPLCONFIGDIR="$XDG_CACHE_HOME/matplotlib"
export PYTHONPYCACHEPREFIX="$XDG_CACHE_HOME/pycache"
export PITPO_OUTPUT_ROOT="${PITPO_OUTPUT_ROOT:-$PITPO_PROJECT_DIR/artifacts}"
export PITPO_ARTIFACT_ROOT="${PITPO_ARTIFACT_ROOT:-$PITPO_OUTPUT_ROOT}"
export PYTHON_BIN="${PYTHON_BIN:-python}"
export PITPO_MODEL_PATH="${PITPO_MODEL_PATH:-Qwen/Qwen2.5-0.5B-Instruct}"
export TOKENIZERS_PARALLELISM=false
export OMP_NUM_THREADS="${OMP_NUM_THREADS:-4}"
export OPENBLAS_NUM_THREADS="${OPENBLAS_NUM_THREADS:-4}"
mkdir -p "$TMPDIR" "$PIP_CACHE_DIR" "$HF_HOME" "$PADDLE_HOME" "$PPNLP_HOME" \
    "$PF_HOME" "$MODELSCOPE_CACHE" "$CUDA_CACHE_PATH" "$TRITON_CACHE_DIR" \
    "$MPLCONFIGDIR" "$PYTHONPYCACHEPREFIX" "$PITPO_OUTPUT_ROOT"
